import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const GENERATED_RELATIVE_PATH =
	"packages/compiler/src/fact-cache-revision.ts";

export function factCacheRevisionEntries(repositoryRoot) {
	const roots = [
		join(repositoryRoot, "packages/compiler/src"),
		join(repositoryRoot, "packages/source/src"),
	];
	const files = [
		...roots.flatMap(sourceFiles),
		join(repositoryRoot, "packages/tree-sitter-liquid/grammar.js"),
		join(repositoryRoot, "packages/tree-sitter-liquid/src/scanner.c"),
		join(repositoryRoot, "packages/tree-sitter-nazare-liquid/grammar.js"),
		join(repositoryRoot, "packages/tree-sitter-nazare-liquid/src/scanner.c"),
	];
	return files
		.map((file) => ({
			path: relative(repositoryRoot, file).split(sep).join("/"),
			contents: readFileSync(file, "utf8"),
		}))
		.filter((entry) => entry.path !== GENERATED_RELATIVE_PATH);
}

export function computeFactCacheRevision(entries) {
	if (entries.length === 0) {
		throw new Error("Fact-cache revision requires at least one input");
	}
	for (const entry of entries) validateEntry(entry);
	const ordered = [...entries].sort((left, right) =>
		left.path.localeCompare(right.path),
	);
	for (let index = 1; index < ordered.length; index += 1) {
		if (ordered[index - 1].path === ordered[index].path) {
			throw new Error(`Duplicate fact-cache revision input ${ordered[index].path}`);
		}
	}
	const hash = createHash("sha256");
	for (const { path, contents } of ordered) {
		hash.update(`${path}\0${contents.length}\0${contents}\0`);
	}
	return `theme-facts-${hash.digest("hex").slice(0, 16)}`;
}

export function computeRepositoryFactCacheRevision(repositoryRoot) {
	return computeFactCacheRevision(factCacheRevisionEntries(repositoryRoot));
}

export function renderFactCacheRevisionModule(revision) {
	if (!/^theme-facts-[a-f0-9]{16}$/.test(revision)) {
		throw new Error(`Invalid fact-cache revision ${revision}`);
	}
	return [
		"// Generated by scripts/generate-fact-cache-revision.mjs. Do not edit.",
		"// Digest of compiler/source adapters and grammar sources, so fact changes",
		"// invalidate every persisted theme fact cache.",
		`export const THEME_FACT_CACHE_REVISION = "${revision}";`,
		"",
	].join("\n");
}

export function generatedFactCacheRevisionPath(repositoryRoot) {
	return join(repositoryRoot, GENERATED_RELATIVE_PATH);
}

function validateEntry(entry) {
	if (
		typeof entry?.path !== "string" ||
		entry.path.length === 0 ||
		entry.path.includes("\\") ||
		entry.path.includes("\0")
	) {
		throw new Error(`Invalid fact-cache revision input path ${entry?.path}`);
	}
	if (typeof entry.contents !== "string") {
		throw new Error(`Invalid contents for fact-cache revision input ${entry.path}`);
	}
}

function sourceFiles(directory) {
	const files = [];
	for (const entry of readdirSync(directory)) {
		const path = join(directory, entry);
		if (statSync(path).isDirectory()) {
			files.push(...sourceFiles(path));
			continue;
		}
		if (entry.endsWith(".ts")) files.push(path);
	}
	return files;
}
